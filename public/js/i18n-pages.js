    // Lugha ya UI: 'en', 'ar'; nyingine zote (sw, both) hutumia Kiswahili.
    const lang = () => {
        const l = (document.documentElement.dataset.uiLanguage || 'en');
        return (l === 'en' || l === 'ar' || l === 'es') ? l : 'sw';
    };

    const locale = () => ({ sw: 'sw-TZ', en: 'en-GB', ar: 'ar', es: 'es-ES' }[lang()]);

    // Lugha ya hadith (tafsiri na vipengele vya hadith): 'en' au 'sw'
    const hadithLang = () => (lang() === 'es' || lang() === 'ar') ? lang() : (document.documentElement.dataset.readingLanguage === 'en' ? 'en' : 'sw');
    const langFor = el => (el && el.closest && el.closest('[data-hadith-scope]')) ? hadithLang() : lang();

    const t = (key, vars, forced) => {
        const L = forced || lang();
        let s = (D[L] && D[L][key]);
        if (s === undefined && L === 'es') s = D.en[key];
        if (s === undefined) s = D.sw[key];
        if (s === undefined) return key;
        if (vars) {
            Object.keys(vars).forEach(k => { s = s.split(':' + k).join(vars[k]); });
        }
        return s;
    };

    const readVars = el => {
        const raw = el.getAttribute('data-i18n-vars');
        if (!raw) return undefined;
        try { return JSON.parse(raw); } catch (_) { return undefined; }
    };

    const known = key => key && Object.prototype.hasOwnProperty.call(D.sw, key);

    // Hubadilisha tu pale maandishi yanapotofautiana (huzuia mizunguko ya MutationObserver).
    const apply = (root) => {
        root = root || document;

        root.querySelectorAll('[data-i18n]').forEach(el => {
            const key = el.getAttribute('data-i18n');
            if (!known(key)) return;
            const v = t(key, readVars(el), langFor(el));
            if (el.textContent !== v) el.textContent = v;
        });

        [['data-i18n-placeholder', 'placeholder'], ['data-i18n-title', 'title'], ['data-i18n-aria-label', 'aria-label']].forEach(([attr, target]) => {
            root.querySelectorAll('[' + attr + ']').forEach(el => {
                const key = el.getAttribute(attr);
                if (!known(key)) return;
                const v = t(key, readVars(el), langFor(el));
                if (el.getAttribute(target) !== v) el.setAttribute(target, v);
            });
        });
    };

    window.BaytI18n = { t, lang, locale, apply };

    let timer = null;
    const schedule = () => {
        if (timer) clearTimeout(timer);
        timer = setTimeout(() => { apply(); }, 30);
    };

    let lastLang = null;
    const onLangMaybeChanged = () => {
        const cur = lang() + '|' + hadithLang();
        apply();
        if (cur !== lastLang) {
            lastLang = cur;
            document.dispatchEvent(new CustomEvent('bayt:lang', { detail: { lang: lang(), hadith: hadithLang() } }));
        }
    };

    const start = () => {
        onLangMaybeChanged();

        new MutationObserver(onLangMaybeChanged).observe(document.documentElement, {
            attributes: true,
            attributeFilter: ['data-ui-language', 'data-reading-language']
        });

        const main = document.querySelector('main') || document.body;
        if (window.MutationObserver && main) {
            new MutationObserver(schedule).observe(main, { childList: true, subtree: true });
        }
    };

    if (document.readyState === 'loading') {
        document.addEventListener('DOMContentLoaded', start);
    } else {
        start();
    }

    document.addEventListener('livewire:navigated', onLangMaybeChanged);
    document.addEventListener('livewire:init', () => {
        if (window.Livewire && typeof window.Livewire.hook === 'function') {
            window.Livewire.hook('morph.updated', schedule);
        }
    });
